import Foundation

extension Keystrokes {

    /// Virtual key codes for the keys this sends.
    public enum Key {

        /// Return.
        public static let `return`: UInt16 = 36

        /// Tab.
        public static let tab: UInt16 = 48

        /// Space.
        public static let space: UInt16 = 49
    }
}
